package aes

import (
	std "crypto/aes"
	"testing"
)

func BenchmarkCryptoNewAES128(b *testing.B) {
	key := []byte{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f}

	b.ReportAllocs()
	for b.Loop() {
		_, err := std.NewCipher(key)
		if err != nil {
			b.Fatal(err)
		}
	}
}

